        else if (page == 3 )
        {
            image1.SetActive(true);
            image2.SetActive(true);
            Debug.Log("3");
            theory.text = "Данные формулы позволяют выполнить зашифрование / расшифрование по Виженеру при замене букв алфавита числами согласно следующей таблице (применительно к русскому алфавиту):";
