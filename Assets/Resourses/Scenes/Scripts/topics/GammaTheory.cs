    public void Pager()
    {
        page++;
        if (page == 2)
        {
            Debug.Log("2");
            theory.text = "Сложение по модулю N. В 1888 г. француз маркиз де Виари в одной из\r\nсвоих научных статей, посвященных криптографии, доказал, что при замене букв исходного сообщения и ключа на числа справедливы формулы:\r\nCi = (Pi + Ki) mod N,\t(3)\r\nPi = (Ci + N - Ki) mod N,\t(4)\r\nгде Pi, Ci – i-ый символ открытого и шифрованного сообщения;\r\nN – количество символов в алфавите;\r\nКi – i-ый символ гаммы (ключа).\r\n";
