using System.Collections;
using System.Collections.Generic;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

public class GammaTheory : MonoBehaviour
{
    [SerializeField] TextMeshProUGUI theory;
    [SerializeField] TextMeshProUGUI theory1;
    [SerializeField] GameObject image1;
    [SerializeField] GameObject image2;
    public int page = 1;
    
    void Start()
    {
        image1.SetActive(false);
        image2.SetActive(false);
        Debug.Log("1");
        theory.text = "\tШифрование гаммированием заключается в том, что символы шифруемого текста складываются с символами некоторой случайной последовательности, называемой гаммой шифра или ключевой гаммой. По стойкости данные шифры относятся к классу совершенных. Стойкость шифрования определяется длиной (периодом) неповторяющейся части гаммы шифра, а также сложностью предугадывания следующих элементов гаммы по предыдущим.\r\n\tШифры гаммирования (аддитивные шифры) являются самыми эффективными с точки зрения стойкости и скорости преобразований (процедур за- шифрования и дешифрования). Для зашифрования и дешифрования используются элементарные арифметические операции – открытое/зашифрованное сообщение и гамма, представленные в числовом виде, складываются друг с другом по модулю (mod, результатом сложения двух целых чисел по модулю является остаток от деления (например, 5+10 mod 4 = 15 mod 4 = 3)).\r\n ";
